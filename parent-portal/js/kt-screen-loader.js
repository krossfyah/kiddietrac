/* ═══════════════════════════════════════════════════════════════════
   KiddieTrac — load each screen's code when the screen is opened.
   (2026-11-02, Anthony approved "Load screens on demand".)

   dashboard.html used to carry a <script> tag for all ~320 files, so every launch
   downloaded and compiled ~11 MB of JavaScript (3.5 MB on the wire) before the first
   screen could draw: 7.4 s on Fast 4G, 23 s on Slow 4G (iPhone, CPU 4x).

   Now the files that only DRAW A SCREEN are not tags. They are listed in
   window.__KT_LAZY (an inline <script> in dashboard.src.html's <head>, generated by
   a census of what every file does while it loads — see the comment there) and
   fetched here the first time a screen that needs them is opened. The shell awaits
   ensure() immediately before it looks the screen up (app-v2-shell.js renderScreen),
   so a screen is never "not available" merely because its file is still in flight.

   WHAT STAYS A TAG (eager): anything that, while loading, adds a listener, a timer,
   an observer, a nav item, a badge, a gate, a sweep (KT.sweepBus), patches another
   file, or provides a function that an eager file calls. Only files that register
   screens and define their own private helpers are lazy.

   MANIFEST ENTRY  "js/<file>.js?v=<stamp>": {
     k: ["role:hash", ...]  screen keys the file registers (the shell's lookup keys)
     h: ["hash", ...]       hashes drawn through screen-legacy-shim.js bridges (KT.X.render)
     d: ["<file>.js", ...]  lazy files it calls into — loaded first, in page order
     a: ["<file>.js", ...]  EAGER files that patch this one at load; run again after it
     p: ["role:hash", ...]  keys a LATER page file also registers: never overwrite those
     s: ["KT.name", ...]    functions eager code calls: a stub loads the file, then calls
   }
   The key has no leading slash on purpose: deploy.py re-stamps it like a tag
   (`python3 ~/deploy.py … <file>.js` works for a lazy file exactly as for an eager
   one), while kt-update-check.js's tag fingerprint ("/js/…") never mistakes the
   manifest for a second copy of the page's scripts.

   FAILS SAFE. A 404 or offline load resolves false; the shell then says the page did
   not load (with Retry) instead of drawing something else, and the next visit retries.
   ═══════════════════════════════════════════════════════════════════ */
(function (w, d) {
  'use strict';
  var KT = (w.KT = w.KT || {});
  if (KT.screenLoader && KT.screenLoader.v2) { return; }

  var RAW = w.__KT_LAZY || {};
  var M = {};          // file name -> entry (+ .url)
  var byKey = {};      // 'role:hash' -> [file]
  var byHash = {};     // 'hash' -> [file]   (any role; shim bridges + every key's hash)
  var bridged = {};    // 'hash' -> [file]   (shim bridges only)
  var order = [];      // file names in page order (the manifest is written in page order)
  Object.keys(RAW).forEach(function (k) {
    var name = k.split('?')[0].replace(/^\/?js\//, '');
    var e = RAW[k] || {};
    e.url = '/' + k.replace(/^\/+/, '');
    M[name] = e; order.push(name);
    (e.k || []).forEach(function (key) {
      (byKey[key] = byKey[key] || []).push(name);
      var h = key.slice(key.indexOf(':') + 1);
      (byHash[h] = byHash[h] || []).push(name);
    });
    (e.h || []).forEach(function (h) {
      (bridged[h] = bridged[h] || []).push(name);
      (byHash[h] = byHash[h] || []).push(name);
    });
  });
  var rank = {}; order.forEach(function (n, i) { rank[n] = i; });

  var loaded = {};     // file -> Promise<boolean>
  var reran = {};      // eager "after" file -> Promise
  var ran = {};        // file -> true once it executed (for the keep guard)

  function tagUrl(name) {
    var t = d.querySelector('script[src*="/js/' + name + '"]:not([data-kt-lazy])');
    return t ? t.getAttribute('src') : null;
  }

  function addScript(url, name, rerun) {
    return new Promise(function (resolve) {
      var s = d.createElement('script');
      s.src = url;
      s.async = false;                       // execute in insertion order: deps, file, afters
      s.setAttribute('data-kt-lazy', rerun ? 'rerun' : '1');
      s.onload = function () { resolve(true); };
      s.onerror = function () { try { s.remove(); } catch (e) {} resolve(false); };
      (d.body || d.documentElement).appendChild(s);
    });
  }

  function one(name) {
    if (loaded[name]) { return loaded[name]; }
    var e = M[name];
    if (!e) { return Promise.resolve(true); }
    var p = addScript(e.url, name, false).then(function (ok) {
      if (!ok) { delete loaded[name]; return false; }
      ran[name] = true;
      return true;
    });
    loaded[name] = p;
    // Eager files that patched this one when the page was built from tags: run them again
    // AFTER it (async=false keeps the order), so the patch lands on the fresh copy too.
    (e.a || []).forEach(function (af) {
      if (reran[name + '>' + af]) { return; }
      var u = tagUrl(af); if (!u) { return; }
      reran[name + '>' + af] = addScript(u, af, true);
    });
    return p;
  }

  /* A file plus everything it calls into, in page order (the order the tags had). */
  function withDeps(names) {
    var seen = {}, out = [];
    names.forEach(function (n) {
      if (!M[n]) { return; }
      (M[n].d || []).concat([n]).forEach(function (x) { if (M[x] && !seen[x]) { seen[x] = 1; out.push(x); } });
    });
    return out.sort(function (a, b) { return rank[a] - rank[b]; });
  }

  function load(names) {
    var list = withDeps(names);
    if (!list.length) { return Promise.resolve(true); }
    return Promise.all(list.map(one)).then(function (r) {
      return r.every(Boolean);
    }, function () { return false; });
  }

  function user() {
    try { return JSON.parse(sessionStorage.getItem('kt_user') || localStorage.getItem('kt_user') || '{}') || {}; } catch (e) { return {}; }
  }
  function hasRole(u, r) { return !!(u && Array.isArray(u.roles) && u.roles.indexOf(r) !== -1); }

  function filesFor(role, hash) {
    var base = hash.split('/')[0];
    var out = [];
    var push = function (arr) { (arr || []).forEach(function (n) { if (out.indexOf(n) === -1) { out.push(n); } }); };
    if (!role) { push(byHash[hash]); push(byHash[base]); return out; }
    var u = user();
    var plat = hasRole(u, 'platform_admin');
    try { plat = plat || sessionStorage.getItem('kt_is_platform_admin') === '1'; } catch (e) {}
    var roles = [role];
    if (plat) { roles.push('platform_admin'); }
    if (hasRole(u, 'reseller_admin')) { roles.push('reseller_admin'); }
    roles.forEach(function (r) { push(byKey[r + ':' + hash]); if (base !== hash) { push(byKey[r + ':' + base]); } });
    push(bridged[hash]); if (base !== hash) { push(bridged[base]); }
    return out;
  }

  function registered(role, hash) {
    var S = KT.Shell; if (!S || !S.screenFn) { return true; }
    var base = hash.split('/')[0];
    return !!(S.screenFn(role + ':' + hash) || S.screenFn('platform_admin:' + hash)
      || S.screenFn('reseller_admin:' + hash) || S.screenFn(role + ':' + base) || S.screenFn('platform_admin:' + base));
  }

  /**
   * Make sure the screen for `hash` (as `role` sees it) can be drawn. Resolves true when
   * everything it needs has run, false if a file could not be fetched (offline / 404).
   * role null = whatever registers that hash, for any role.
   */
  function ensure(role, hash) {
    hash = String(hash || '').replace(/^#/, '').split('?')[0];
    var names = filesFor(role, hash);
    /* Nothing registers this hash at all: the shell falls back to the role's dashboard
       (or the parent's Today), so make sure that one is here. */
    if (role && !names.length && !registered(role, hash)) {
      names = filesFor(role, 'dashboard');
      if (!names.length && role === 'guardian') { names = filesFor('guardian', 'today'); }
    }
    return load(names);
  }

  /* ── never overwrite a screen a later page file owns ─────────────────────────────
     When two files register the same key, the one later in the page wins. A lazy file
     loads after every tag, so for each key where a LATER file also registers (the
     manifest's `p`), its registration is skipped if that key is already taken. */
  (function guard() {
    var S = KT.Shell;
    if (!S || S.__placeholder || S.__ktLazyGuard || !S.registerScreen) { return; }
    var keepOf = {};
    Object.keys(M).forEach(function (n) { if ((M[n].p || []).length) { keepOf[n] = M[n].p; } });
    var orig = S.registerScreen;
    S.registerScreen = function (name, fn) {
      try {
        var cs = d.currentScript;
        var file = cs && cs.getAttribute('data-kt-lazy') === '1' ? (cs.getAttribute('src') || '').split('?')[0].replace(/^.*\/js\//, '') : '';
        if (file && keepOf[file] && keepOf[file].indexOf(name) !== -1 && S.screenFn && S.screenFn(name)) { return; }
      } catch (e) {}
      return orig.apply(this, arguments);
    };
    S.__ktLazyGuard = true;
  })();

  /* ── stubs: eager code calls a few functions that live in lazy files ─────────────
     (KT.openMyAccount from the top bar, KT.openUserRecord from an avatar, …). Until the
     file arrives the name answers with a stub that fetches it and then makes the call.
     The real file assigns the name unconditionally, replacing the stub. */
  Object.keys(M).forEach(function (n) {
    (M[n].s || []).forEach(function (full) {
      var nm = full.replace(/^KT\./, '');
      if (typeof KT[nm] !== 'undefined') { return; }
      var stub = function () {
        var a = arguments, t = this;
        return load([n]).then(function () {
          var real = KT[nm];
          if (typeof real === 'function' && real !== stub) { return real.apply(t, a); }
        });
      };
      stub.__ktLazyStub = true;
      KT[nm] = stub;
    });
  });

  /* screen-v22p59.js (Support tickets, lazy) remembers the screen you were on before you
     opened #tickets, to pre-fill a problem report. Its listener now arrives with it, so
     keep that memory until it does. Same key, same rule as its own listener. */
  w.addEventListener('hashchange', function (e) {
    if (KT.V22p59) { return; }
    try {
      var old = String(e.oldURL || '').split('#')[1] || '';
      if (old && !/^tickets/.test(old)) { sessionStorage.setItem('kt_tk_from', old.split('?')[0]); }
    } catch (x) {}
  });

  /* Start fetching the first screen's files now (no execution) — the head preloaded a
     guess; this is the exact answer, from the shell's own home/role rules. */
  try {
    var S0 = KT.Shell, u0 = user();
    if (S0 && S0.Roles && S0.homeHashForRole && u0 && u0.roles) {
      var r0 = S0.Roles.primaryRoleOf(u0);
      var h0 = (location.hash || '').replace(/^#/, '').split('?')[0] || (r0 ? S0.homeHashForRole(r0) : '');
      if (r0 && h0) {
        withDeps(filesFor(r0, h0)).forEach(function (n) {
          var url = M[n].url;
          if (d.querySelector('link[rel="preload"][href="' + url + '"]')) { return; }
          var l = d.createElement('link'); l.rel = 'preload'; l.as = 'script'; l.href = url;
          d.head.appendChild(l);
        });
      }
    }
  } catch (e) {}

  KT.screenLoader = {
    v2: true,
    ensure: ensure,
    load: function (names) { return load([].concat(names).map(function (n) { return String(n).replace(/^.*\/js\//, '').split('?')[0]; })); },
    /* For a support call: what this tab has fetched on demand, and what it has not. */
    stats: function () {
      var got = Object.keys(loaded);
      return { lazy: order.length, loaded: got.length, files: got };
    },
  };
})(window, document);
