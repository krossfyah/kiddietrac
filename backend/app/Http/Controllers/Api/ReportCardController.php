    public function index(Request $request): JsonResponse
    {
        if ($request->boolean('archived')) {
            return $this->archived($request);   // same admin-only guard as GET /report-cards/archived
        }
        $this->assertStaff($request);
        $u = $request->user();
        $agencyId = (int) $this->resolveAgencyId($request);
        abort_unless($agencyId > 0, 403, 'Select an agency to see its report cards.');

        $q = DB::table('report_cards as r')
            ->join('children as ch', 'ch.id', '=', 'r.child_id')
            ->join('families as f', 'f.id', '=', 'ch.family_id')
            ->join('centres as c', 'c.id', '=', 'f.centre_id')
            ->leftJoin('rooms as rm', 'rm.id', '=', 'ch.primary_room_id')
            ->leftJoin('users as gu', 'gu.id', '=', 'r.generated_by_user_id')
            ->leftJoin('users as su', 'su.id', '=', 'r.submitted_by_user_id')
            ->where('c.agency_id', $agencyId)
            ->whereNull('f.deleted_at');
        \App\Support\Live::children($q, 'ch');
        \App\Support\Live::centres($q, 'c');

        $centreIds = \App\Support\CentreScope::ids($request, $agencyId);   // null = agency-wide
        $roles = \App\Support\AgencyRole::names($request);
        if ($centreIds !== null) {
            if (in_array('centre_director', $roles, true)) {
                $q->whereIn('f.centre_id', $centreIds ?: [0]);
            } else {
                $kids = \App\Support\Visibility::liveChildIds($agencyId, $u);
                $mine = DB::table('report_cards')->where('generated_by_user_id', $u->id)->pluck('child_id', 'id')->all();
                $ownIds = [];
                foreach ($mine as $cardId => $childId) {
                    if ($this->canAccessChildId($u, (int) $childId)) {
                        $ownIds[] = (int) $cardId;
                    }
                }
                $q->where(function ($w) use ($kids, $ownIds) {
                    $w->whereIn('r.child_id', $kids ?: [0])->orWhereIn('r.id', $ownIds ?: [0]);
                });
            }
