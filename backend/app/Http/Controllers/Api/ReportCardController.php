                        'model' => $model,
                        'max_tokens' => 500,
                        'messages' => [['role' => 'user', 'content' => $prompt]],
                    ]);
                    $text = $res->ok() ? trim(\App\Support\AiConfig::text($res->json()) ?? '') : '';
                } catch (\Throwable $e) {
                    $text = '';
                }
            }
            if ($text === '') {
                $text = $this->templateNarrative($child->first_name, (string) $data['term'], $area['label'],
                    lcfirst(rtrim((string) $area['hint'], '.')), $obsForArea, $eventCounts);
            }
            $narratives[$area['key']] = $text;
        }

        $nextSteps = '';
        if ($key) {
            $nextPrompt = "Based on this child's profile, write 3 specific next-steps suggestions for {$child->first_name}'s continued growth. Return as a short numbered list.";
            try {
                \App\Support\AiFresh::as('report_next_steps', \App\Support\AiFresh::agencyFrom(['child_id' => $childId]));
                $res = Http::withHeaders([
                    'x-api-key' => $key, 'anthropic-version' => '2023-06-01', 'content-type' => 'application/json',
                ])->timeout(45)->post('https://api.anthropic.com/v1/messages', [
                    'model' => $model,
                    'max_tokens' => 400,
                    'messages' => [['role' => 'user', 'content' => $nextPrompt]],
                ]);
                $nextSteps = $res->ok() ? trim(\App\Support\AiConfig::text($res->json()) ?? '') : '';
            } catch (\Throwable $e) {
                $nextSteps = '';
            }
        }
        if ($nextSteps === '') {
            $nextSteps = $this->templateNextSteps($child->first_name, $observations, $fw);
        }

        // Never a SENT card (2026-11-26): an approved card is changed only through a new version.
        $exists = DB::table('report_cards')->where('child_id', $child->id)->where('term', $data['term'])
            ->where('status', '!=', 'sent')->whereNull('replaces_id')->orderByDesc('id')->first();
        $payload = [
            'child_id' => $child->id,
            'term' => $data['term'],
            'generated_by_user_id' => $byUserId,
            // HDLH keys match the four legacy columns; other frameworks leave them empty.
